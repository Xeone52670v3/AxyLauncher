use std::sync::atomic::{AtomicU8, Ordering};

const LANG_RU: u8 = 0;
const LANG_EN: u8 = 1;
const LANG_UK: u8 = 2;
const LANG_ES: u8 = 3;
const LANG_FR: u8 = 4;
const LANG_DE: u8 = 5;
const LANG_PL: u8 = 6;
const LANG_ZH: u8 = 7;
const LANG_JA: u8 = 8;

static CURRENT_LANG: AtomicU8 = AtomicU8::new(LANG_RU);

pub fn detect_system_lang_label() -> &'static str {
    let raw = std::env::var("LC_ALL")
        .or_else(|_| std::env::var("LC_MESSAGES"))
        .or_else(|_| std::env::var("LANG"))
        .unwrap_or_default()
        .to_lowercase();
    if raw.starts_with("uk") {
        "Українська (UA)"
    } else if raw.starts_with("es") {
        "Español (ES)"
    } else if raw.starts_with("fr") {
        "Français (FR)"
    } else if raw.starts_with("de") {
        "Deutsch (DE)"
    } else if raw.starts_with("pl") {
        "Polski (PL)"
    } else if raw.starts_with("zh") {
        "中文 (ZH)"
    } else if raw.starts_with("ja") {
        "日本語 (JA)"
    } else if raw.starts_with("en") {
        "English (US)"
    } else {
        "Русский (RU)"
    }
}

pub fn lang_id_from_label(lang: &str) -> u8 {
    let l = lang.to_lowercase();
    if l.contains("english") || l.contains("(us)") || l.contains("(en)") || l == "en" {
        LANG_EN
    } else if l.contains("україн") || l.contains("(ua)") || l.contains("(uk)") || l == "uk" || l == "ua" {
        LANG_UK
    } else if l.contains("español") || l.contains("espanol") || l.contains("(es)") || l == "es" {
        LANG_ES
    } else if l.contains("français") || l.contains("francais") || l.contains("(fr)") || l == "fr" {
        LANG_FR
    } else if l.contains("deutsch") || l.contains("(de)") || l == "de" {
        LANG_DE
    } else if l.contains("polski") || l.contains("(pl)") || l == "pl" {
        LANG_PL
    } else if l.contains("中文") || l.contains("(zh)") || l == "zh" {
        LANG_ZH
    } else if l.contains("日本語") || l.contains("(ja)") || l == "ja" {
        LANG_JA
    } else {
        LANG_RU
    }
}

pub fn set_language(lang: &str, use_system_locale: bool) {
    let effective = if use_system_locale {
        detect_system_lang_label()
    } else {
        lang
    };
    CURRENT_LANG.store(lang_id_from_label(effective), Ordering::Relaxed);
}

pub fn apply_language(ui: &MainWindow, lang: &str, use_system_locale: bool) {
    set_language(lang, use_system_locale);
    let tr = ui.global::<Tr>();
    tr.set_rev(tr.get_rev().wrapping_add(1));
}

pub fn translate_current(key: &str) -> &str {
    let id = CURRENT_LANG.load(Ordering::Relaxed);
    if id == LANG_RU {
        return key;
    }
    translate_by_id(key, id).unwrap_or(key)
}

#[cfg(test)]
pub fn translate<'a>(key: &'a str, lang: &str) -> &'a str {
    let id = lang_id_from_label(lang);
    if id == LANG_RU {
        return key;
    }
    translate_by_id(key, id).unwrap_or(key)
}

